/**
 * 판정(정상/주의/위험) 없이 "그냥 분류"만 시각적으로 구분하고 싶을 때 쓴다.
 * 예: 완제품 검사이력처럼 합격/불량 필드가 없는 카드에서 품목별로 색만 다르게.
 *
 * 값 목록을 미리 정해두고 색을 매핑하지 않는다 — 실제 운영 데이터에 어떤 품목이
 * 몇 종류나 있을지 모르는 상태에서 "6mm/8mm/10mm"처럼 지금 목데이터에만 있는
 * 값을 기준으로 하드코딩하면, 나중에 실제 데이터에 다른 품목이 들어오는 순간
 * 깨진다. 대신 문자열을 해시해서 고정 팔레트에서 순서대로 뽑는다 — 같은 문자열은
 * 항상 같은 색을 받고, 새로운 값이 나타나도 코드 변경 없이 자동으로 색이 배정된다.
 *
 * 상태(정상/주의/위험/정지)에 쓰는 초록/주황/빨강 계열은 "판정처럼 보일 수 있어"
 * 일부러 뺐다 — 이 색은 순수 분류용이라는 걸 명확히 하기 위해서다.
 */
// cyan/blue/violet/fuchsia/pink 5색은 전부 색상환에서 청록~보라~분홍 구간에
// 몰려 있어서, 실제로 hash가 그중 세 개를 뽑으면(예: violet/blue/fuchsia) 다
// "파란 계열"로 보였다 — 색 이름이 다른 것과 실제로 구분되어 "보이는" 것은
// 다른 문제였다. dataviz 스킬의 검증된 categorical 팔레트에서, 우리 앱의
// 상태색(정상=초록/주의=주황/위험=빨강)과 색상환상 겹치지 않는 blue/violet/
// magenta 세 개만 뽑아 썼다 — validate_palette.js로 CVD·명도 대비를 실제로
// 검증한 조합이라 "이 정도면 구분되겠지"가 아니라 확인된 값이다.
// 상태색을 피하면서 서로 확실히 구분되는 색은 검증 결과 딱 3개까지였다(시안·
// 남색·청록 등 여러 후보를 넣어봤지만 4개째부터는 항상 CVD나 명도대비 중 하나가
// 깨졌다). 품목이 4종류 넘어가면 그중 하나와 색이 겹치지만, 카드 제목에 품목명이
// 이미 텍스트로 보이므로 실제 정보 손실은 없다 — 상태색과 헷갈릴 여지를 없애는
// 쪽을 우선했다.
const CATEGORY_PALETTE = ["bg-[#2a78d6]", "bg-[#4a3aa7]", "bg-[#e87ba4]"] as const

export function categoryAccentClass(key: string): string {
  let hash = 0
  for (let i = 0; i < key.length; i++) {
    hash = (hash * 31 + key.charCodeAt(i)) >>> 0
  }
  return CATEGORY_PALETTE[hash % CATEGORY_PALETTE.length]
}
